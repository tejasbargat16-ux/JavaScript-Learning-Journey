// JavaScript Learning Journey
// Day 02 - Practice Solutions


// ========================================
// Problem 1 — Calculator
// ========================================

let a = 50;
let b = 10;

console.log("Addition:", a + b);
console.log("Subtraction:", a - b);
console.log("Multiplication:", a * b);
console.log("Division:", a / b);
console.log("Remainder:", a % b);


// ========================================
// Problem 2 — Comparison
// ========================================

let age = 20;

console.log("Age greater than 18:", age > 18);
console.log("Age equal to 20:", age === 20);
console.log("Age less than or equal to 25:", age <= 25);


// ========================================
// Problem 3 — Rectangle
// ========================================

let length = 25;
let width = 15;

let area = length * width;
let perimeter = 2 * (length + width);

console.log("Area:", area);
console.log("Perimeter:", perimeter);


// ========================================
// Problem 4 — Shopping Bill
// ========================================

let productPrice = 799;
let quantity = 3;

let totalBill = productPrice * quantity;

console.log("Total Bill:", totalBill);


// ========================================
// Problem 5 — Type Conversion
// ========================================

let marks = "85";

let convertedMarks = Number(marks);

console.log("Marks:", convertedMarks);
console.log("Type:", typeof convertedMarks);


// ========================================
// Problem 6 — Percentage
// ========================================

let totalMarks = 500;
let obtainedMarks = 425;

let percentage = (obtainedMarks / totalMarks) * 100;

console.log("Percentage:", percentage);
