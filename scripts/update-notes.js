#!/usr/bin/env node
/*
 * update-notes.js — zero-dependency notes builder.
 *
 *  1) Reads every Day-XX/README.md  -> builds  INTERVIEW_NOTES.md
 *       (collects "## 🎤 Interview Q&A" + "## ⚠️ Common Mistakes" sections)
 *  2) Reads every DSA/**.js header    -> builds  DSA/README.md
 *       (tracker table, counts by difficulty/topic, revise list)
 *
 * Run:  node scripts/update-notes.js
 * Output is deterministic (no timestamps) so git only sees real changes.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DSA_DIR = path.join(ROOT, 'DSA');

const stripComments = (s) => s.replace(/<!--[\s\S]*?-->/g, '');
const esc = (s) => String(s || '—').replace(/\|/g, '\\|');

function writeIfChanged(file, content) {
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (old === content) return console.log(`= unchanged  ${path.relative(ROOT, file)}`);
  fs.writeFileSync(file, content);
  console.log(`+ updated    ${path.relative(ROOT, file)}`);
}

/* ---------- 1. Interview notes ---------- */

// Returns the body of the first "## ..." section whose heading matches `re`.
function getSection(md, re) {
  const out = [];
  let on = false;
  let fence = false;
  for (const line of md.split('\n')) {
    if (/^\s*```/.test(line)) fence = !fence;
    if (!fence && /^##\s/.test(line)) {
      if (on) break;
      if (re.test(line)) { on = true; continue; }
    }
    if (on) out.push(line);
  }
  return stripComments(out.join('\n')).trim();
}

const TOPIC_FALLBACKS = {
  'Day-01': 'JavaScript Basics',
  'Day-02': 'Operators, Input & Type Conversion',
  'Day-03': 'Conditional Statements',
  'Day-04': 'Loops',
  'Day-05': 'Functions',
  'Day-06': 'Arrays',
  'Day-07': 'Objects',
  'Day-08': 'Strings & String Methods',
  'Day-09': 'Array Methods',
  'Day-10': 'Destructuring & Spread',
  'Day-11': 'Callbacks & Higher-Order Functions',
  'Day-12': 'Arrow Functions & Task Manager'
};

function collectDays() {
  return fs
    .readdirSync(ROOT, { withFileTypes: true })
    .filter((d) => d.isDirectory() && /^Day-\d+$/.test(d.name))
    .map((d) => d.name)
    .sort((a, b) => parseInt(a.slice(4), 10) - parseInt(b.slice(4), 10))
    .map((name) => {
      const f = path.join(ROOT, name, 'README.md');
      const base = { name, topic: TOPIC_FALLBACKS[name] || '—', qa: '', mistakes: '', qCount: 0 };
      if (!fs.existsSync(f)) return base;
      const md = fs.readFileSync(f, 'utf8');
      const t = md.match(/^#+\s*Day\s*\d+\s*[:\-–—]\s*(.+)$/mi);
      const qa = getSection(md, /interview/i);
      return {
        ...base,
        topic: t ? t[1].trim() : (TOPIC_FALLBACKS[name] || '—'),
        qa,
        mistakes: getSection(md, /common mistakes/i),
        qCount: (qa.match(/^\*\*Q\d*[.:)]/gm) || []).length,
      };
    });
}

function buildInterview(days) {
  const total = days.reduce((s, d) => s + d.qCount, 0);
  const L = [
    '<!-- AUTO-GENERATED by scripts/update-notes.js — do not edit by hand. -->',
    '<!-- Edit the "Interview Q&A" section inside Day-XX/README.md instead. -->',
    '',
    '# 🎤 Interview Notes',
    '',
    `Auto-compiled from every day's notes. **${total}** questions across **${days.filter((d) => d.qCount).length}** days.`,
    '',
    '| Day | Topic | Questions | Mistakes noted |',
    '|:----|:------|:---------:|:--------------:|',
    ...days.map(
      (d) => `| [${d.name}](${d.name}/README.md) | ${esc(d.topic)} | ${d.qCount || '—'} | ${d.mistakes ? '✅' : '—'} |`
    ),
    '',
  ];
  for (const d of days) {
    if (!d.qa && !d.mistakes) continue;
    L.push('---', '', `## ${d.name} — ${d.topic}`, '');
    if (d.qa) L.push(d.qa, '');
    if (d.mistakes) L.push('**⚠️ Common mistakes**', '', d.mistakes, '');
  }
  return L.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

/* ---------- 2. DSA tracker ---------- */

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return walk(p);
    return e.name.endsWith('.js') && !e.name.startsWith('_') ? [p] : [];
  });
}

function parseHeader(src) {
  const meta = {};
  for (const line of src.split('\n').slice(0, 20)) {
    const m = line.match(/^\/\/\s*(Problem|Link|Pattern|Difficulty|Time|Space|Status):\s*(.+?)\s*$/i);
    if (m) meta[m[1].toLowerCase()] = m[2];
  }
  return meta;
}

const cap = (s) => (s ? s[0].toUpperCase() + s.slice(1).toLowerCase() : '—');
const statusIcon = (s = 'solved') => {
  s = s.toLowerCase();
  if (s.startsWith('solved')) return '✅ solved';
  if (s.startsWith('revise')) return '🔁 revise';
  return '🟡 ' + s;
};

function collectDsa() {
  if (!fs.existsSync(DSA_DIR)) return [];
  return walk(DSA_DIR)
    .sort()
    .map((f) => {
      const rel = path.relative(DSA_DIR, f).split(path.sep).join('/');
      const meta = parseHeader(fs.readFileSync(f, 'utf8'));
      return {
        rel,
        topic: rel.includes('/') ? rel.split('/')[0] : 'misc',
        title: meta.problem || path.basename(f, '.js'),
        link: meta.link,
        pattern: meta.pattern,
        diff: cap(meta.difficulty),
        time: meta.time,
        space: meta.space,
        status: statusIcon(meta.status),
      };
    });
}

const countBy = (arr, key) =>
  arr.reduce((m, x) => ((m[x[key]] = (m[x[key]] || 0) + 1), m), {});

function buildDsa(items) {
  const byDiff = countBy(items, 'diff');
  const byTopic = countBy(items, 'topic');
  const revise = items.filter((i) => i.status.includes('revise'));
  const L = [
    '<!-- AUTO-GENERATED by scripts/update-notes.js — do not edit by hand. -->',
    '<!-- Add a problem: bash scripts/new.sh dsa <topic> <slug> "<Title>" <Easy|Medium|Hard> "<Pattern>" -->',
    '',
    '# 🧠 DSA Tracker',
    '',
    `Theory, patterns and the 6-week plan live in [NOTES.md](NOTES.md).`,
    '',
    `**Total solved/tracked: ${items.length}**  ·  ` +
      ['Easy', 'Medium', 'Hard'].map((d) => `${d}: ${byDiff[d] || 0}`).join('  ·  '),
    '',
    '## By topic',
    '',
    Object.keys(byTopic).length
      ? Object.entries(byTopic).sort().map(([t, n]) => `- \`${t}\` — ${n}`).join('\n')
      : '_No problems yet._',
    '',
    '## 🔁 Revise list',
    '',
    revise.length ? revise.map((i) => `- [${i.title}](${i.rel}) — ${i.pattern || '—'}`).join('\n') : '_Nothing to revise._',
    '',
    '## All problems',
    '',
    '| # | Problem | Topic | Pattern | Diff | Time | Space | Status |',
    '|:-:|:--------|:------|:--------|:----:|:----:|:-----:|:-------|',
    ...items.map(
      (i, n) =>
        `| ${n + 1} | [${esc(i.title)}](${i.rel})${i.link ? ` [🔗](${i.link})` : ''} | ${esc(i.topic)} | ${esc(i.pattern)} | ${i.diff} | ${esc(i.time)} | ${esc(i.space)} | ${i.status} |`
    ),
  ];
  return L.join('\n') + '\n';
}

/* ---------- main ---------- */

writeIfChanged(path.join(ROOT, 'INTERVIEW_NOTES.md'), buildInterview(collectDays()));
if (fs.existsSync(DSA_DIR)) {
  writeIfChanged(path.join(DSA_DIR, 'README.md'), buildDsa(collectDsa()));
} else {
  console.log('! DSA/ folder not found — skipped DSA tracker');
}
